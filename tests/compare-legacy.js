#!/usr/bin/env node
// Runs the musical reference suite with the 1.1.0 algorithm (tests/legacy/core-1.1.0.js) and with
// the current one, and writes tests/COMPARISON.md (before/after per group, every changed case).
//
//   node tests/compare-legacy.js
"use strict";
const fs = require("fs");
const path = require("path");
const lib = require("./lib.js");
const runner = require("./suite-runner.js");

const legacy = runner.runSuite(lib.loadLegacy());
const current = runner.runSuite(lib.loadQml().Core());

const groups = {};
legacy.forEach((r, i) => {
    const g = r.case.group;
    groups[g] = groups[g] || { n: 0, oldPass: 0, newPass: 0, oldCanon: 0, newCanon: 0, oldImp: 0, newImp: 0 };
    const x = groups[g], c = current[i];
    x.n++;
    if (r.pass) { x.oldPass++; } if (c.pass) { x.newPass++; }
    if (r.cls === "CANONICAL") { x.oldCanon++; } if (c.cls === "CANONICAL") { x.newCanon++; }
    if (r.cls === "PHYSICALLY IMPOSSIBLE") { x.oldImp++; } if (c.cls === "PHYSICALLY IMPOSSIBLE") { x.newImp++; }
});

let md = "# Version 1.1.0 vs version 2.0.0 on the musical reference suite\n\n" +
    "Generated by `node tests/compare-legacy.js`. Same cases, same classifier (tests/lib.js), " +
    "same pass criteria as `tests/run-tests.js`.\n\n" +
    "| group | cases | pass 1.1.0 | pass 2.0.0 | canonical 1.1.0 | canonical 2.0.0 | impossible 1.1.0 | impossible 2.0.0 |\n" +
    "|---|---|---|---|---|---|---|---|\n";
const tot = { n: 0, oldPass: 0, newPass: 0, oldCanon: 0, newCanon: 0, oldImp: 0, newImp: 0 };
Object.keys(groups).forEach(g => {
    const x = groups[g];
    Object.keys(tot).forEach(k => { tot[k] += x[k]; });
    md += "| " + g + " | " + x.n + " | " + x.oldPass + " | " + x.newPass + " | " + x.oldCanon + " | " + x.newCanon +
          " | " + x.oldImp + " | " + x.newImp + " |\n";
});
md += "| **total** | " + tot.n + " | " + tot.oldPass + " | " + tot.newPass + " | " + tot.oldCanon + " | " + tot.newCanon +
      " | " + tot.oldImp + " | " + tot.newImp + " |\n\n";

md += "## Every case whose fingering changed\n\n| group | case | expected | 1.1.0 | class | 2.0.0 | class |\n|---|---|---|---|---|---|---|\n";
let changed = 0, regress = [];
legacy.forEach((r, i) => {
    const c = current[i];
    if (r.fingers.join("") === c.fingers.join("")) { return; }
    changed++;
    if (r.pass && !c.pass) { regress.push(c.case.name); }
    md += "| " + r.case.group + " | " + r.case.name + " | " + (r.case.expected ? r.case.expected.join("") : "–") + " | " +
          r.fingers.join("") + " | " + r.cls + " | " + c.fingers.join("") + " | " + c.cls + " |\n";
});
md += "\n" + changed + " of " + legacy.length + " cases changed. Regressions (passed before, fail now): " +
      (regress.length ? regress.join(", ") : "none") + ".\n";

fs.writeFileSync(path.join(__dirname, "COMPARISON.md"), md);
console.log("pass: 1.1.0 " + tot.oldPass + "/" + tot.n + ", 2.0.0 " + tot.newPass + "/" + tot.n +
            "; canonical: " + tot.oldCanon + " -> " + tot.newCanon + "; impossible: " + tot.oldImp + " -> " + tot.newImp +
            "; changed " + changed + "; regressions " + regress.length);
console.log("wrote tests/COMPARISON.md");
